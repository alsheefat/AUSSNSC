package com.aussnsc.app

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.tasks.await

/** Google account picker -> Firebase sign-in -> Firebase ID token (which our server verifies). */
object GoogleAuth {
    suspend fun signIn(context: Context): String {
        // default_web_client_id is generated by the google-services plugin from google-services.json
        val resId = context.resources.getIdentifier("default_web_client_id", "string", context.packageName)
        if (resId == 0) {
            throw ApiException("Google sign-in isn't set up in this build (google-services.json is missing or has no web client). See the setup guide, step Firebase.")
        }
        try {
            val option = GetGoogleIdOption.Builder()
                .setFilterByAuthorizedAccounts(false)
                .setServerClientId(context.getString(resId))
                .build()
            val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
            val result = CredentialManager.create(context).getCredential(context, request)
            val cred = result.credential
            if (cred !is CustomCredential || cred.type != GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                throw ApiException("Google sign-in failed. Please try again.")
            }
            val google = GoogleIdTokenCredential.createFrom(cred.data)
            val auth = FirebaseAuth.getInstance()
            val signedIn = auth.signInWithCredential(GoogleAuthProvider.getCredential(google.idToken, null)).await()
            val token = signedIn.user?.getIdToken(false)?.await()?.token
                ?: throw ApiException("Could not get a sign-in token from Firebase.")
            auth.signOut() // the school server keeps the session from here on
            return token
        } catch (e: ApiException) {
            throw e
        } catch (e: GetCredentialCancellationException) {
            throw ApiException("Sign-in cancelled.")
        } catch (e: NoCredentialException) {
            throw ApiException("No Google account found on this phone. Add one in Android Settings and try again.")
        } catch (e: GetCredentialException) {
            throw ApiException("Google sign-in failed: ${e.message ?: e.type}")
        } catch (e: Exception) {
            throw ApiException("Google sign-in failed: ${e.message ?: "unknown error"}")
        }
    }
}
